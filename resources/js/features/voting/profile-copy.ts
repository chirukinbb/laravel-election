export const profileCopy: Readonly<Record<Locale, ProfileCopy>> =
  Object.fromEntries(
    Object.entries(values).map(([locale, translations]) => {
      const copy = Object.fromEntries(
        keys.map((key, index) => [key, translations[index]]),
      ) as Record<CopyKey, string>;
      const [
        required,
        tooLong,
        invalidCountry,
        invalidDate,
        maxContributions,
        maxLinks,
      ] = errorValues[locale as Locale];
      return [
        locale,
        {
          ...copy,
          errors: {
            required,
            tooLong,
            invalidCountry,
            invalidDate,
            maxContributions,
            maxLinks,
            reasonLength: copy.invalidReason,
            invalidUrl: copy.invalidLink,
          },
        },
      ];
    }),
  ) as Record<Locale, ProfileCopy>;

export function getProfileCopy(locale: Locale): ProfileCopy {
  return profileCopy[locale];
}
